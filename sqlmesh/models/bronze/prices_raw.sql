MODEL (
  name        bronze.prices_raw,
  kind        INCREMENTAL_BY_TIME_RANGE (
    time_column date,
    batch_size  90
  ),
  description 'Couche Bronze — sélection des colonnes utiles de prices_raw. Aucune transformation métier.',
  columns (
    id                                  BIGINT,
    product_code                        TEXT,
    price                               NUMERIC,
    price_is_discounted                 BOOLEAN,
    price_without_discount              NUMERIC,
    discount_type                       TEXT,
    price_per                           TEXT,
    currency                            TEXT,
    date                                DATE,
    proof_type                          TEXT,
    proof_date                          DATE,
    proof_currency                      TEXT,
    location_osm_id                     BIGINT,
    location_osm_type                   TEXT,
    location_osm_display_name           TEXT,
    location_osm_tag_key                TEXT,
    location_osm_tag_value              TEXT,
    location_osm_address_postcode       TEXT,
    location_osm_address_city           TEXT,
    location_osm_address_country        TEXT,
    location_osm_address_country_code   TEXT,
    location_osm_lat                    NUMERIC,
    location_osm_lon                    NUMERIC,
    location_osm_name                   TEXT,
    location_osm_brand                  TEXT,
    location_type                       TEXT,
    inserted_at                         TIMESTAMP,
    _ingestion_run_id                   TEXT
  )
);

SELECT
  id,
  product_code,
  price,
  price_is_discounted,
  price_without_discount,
  discount_type,
  price_per,
  currency,
  date,
  proof_type,
  proof_date,
  proof_currency,
  location_osm_id,
  location_osm_type,
  location_osm_display_name,
  location_osm_tag_key,
  location_osm_tag_value,
  location_osm_address_postcode,
  location_osm_address_city,
  location_osm_address_country,
  location_osm_address_country_code,
  location_osm_lat,
  location_osm_lon,
  location_osm_name,
  location_osm_brand,
  location_type,
  inserted_at,
  _ingestion_run_id::TEXT
FROM public.prices_raw
WHERE date BETWEEN @start_ds AND @end_ds
